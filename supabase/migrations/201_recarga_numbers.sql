-- =====================================================================
-- 201 — The bot collects the recharge numbers (staging first)
--
-- odd/tasks/panel-other-services.md (R2). One Cuban number per recharge (owner). A recharge operation is created when
-- its deposit arrives (cerebro_registrar_deposito, keyword recarga/etecsa/cubacel in the last 24 h); nothing stored the
-- numbers, and a number sent alone went the card way (cerebro_guardar_beneficiario_auto -> a cuban_card row).
--   - crm_registrar_numeros_recarga(conv, text): the Cuban mobiles in the text (8 digits starting 5 or 6, optional
--     +53, spaces/dots/dashes between groups; a 16-digit card or a landline is not one) go to the open recharge, no
--     repeats, panel lock respected, audited (new action automation_recharge_numbers_registered); returns what the
--     recharge still needs. Used by the agent's tool (numbers said by audio) and by:
--   - cerebro_registrar_deposito: a NEW recharge takes the numbers typed since the customer asked for it;
--   - cerebro_guardar_beneficiario_auto: with an open recharge, a number arriving alone is a recharge number.
--
-- Guarded by supabase/staging/assertions/recarga-numbers.sql.
-- ROLLBACK: ROLLBACK-201-recarga-numbers.sql
-- =====================================================================
ALTER TABLE remittance_admin_audit DROP CONSTRAINT remittance_admin_audit_action_chk;
